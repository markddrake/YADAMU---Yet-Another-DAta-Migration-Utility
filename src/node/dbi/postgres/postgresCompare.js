
import YadamuCompare   from '../base/yadamuCompare.js'

class PostgresCompare extends YadamuCompare {    static get SQL_SCHEMA_TABLE_NAMES()    { return _SQL_SCHEMA_TABLE_NAMES }

    static get SQL_SCHEMA_TABLE_ROWS()     { return _SQL_SCHEMA_TABLE_ROWS }
    static get SQL_COMPARE_SCHEMAS()       { return _SQL_COMPARE_SCHEMAS }
    static get SQL_SUCCESS()               { return _SQL_SUCCESS }
    static get SQL_FAILED()                { return _SQL_FAILED }
    static get SQL_SOURCE_DEPENDENCIES()   { return _SQL_SOURCE_DEPENDENCIES }
    static get SQL_GENERATED_COLUMNS()     { return _SQL_GENERATED_COLUMNS }
	
    constructor(dbi,configuration) {
	  super(dbi,configuration)
	}

	async getRowCounts(target) {
	
     
      const results = await this.dbi.executeSQL(PostgresCompare.SQL_SCHEMA_TABLE_ROWS,[target]);
      return results.rows
    }    

    async compareSchemas(source,target,rules) {

      const report = {
        successful : []
       ,failed     : []
      }

      // A DDL_ONLY operation copies no data, so only the DDL is compared.
      if (this.configuration.parameters?.MODE !== 'DDL_ONLY') {

        const compareRules = this.formatCompareRules(rules)
        compareRules.ignoreGeneratedColumns = rules.IGNORE_GENERATED_COLUMNS === true

        // Name each column that YADAMU.COMPARE_SCHEMA leaves out because both databases generate it.
        if (compareRules.ignoreGeneratedColumns) {
          const generated = await this.dbi.executeSQL(PostgresCompare.SQL_GENERATED_COLUMNS,[source,target])
          generated.rows.forEach(([tableName,columnName]) => {
            this.LOGGER.qa([`COMPARE`,`${this.configuration.source.vendor}`,`${this.configuration.target.vendor}`,tableName],`Column "${columnName}" is generated by both the source and the target database. Not compared.`)
          })
        }

        await this.dbi.executeSQL(PostgresCompare.SQL_COMPARE_SCHEMAS,[source,target,compareRules])

        const successful = await this.dbi.executeSQL(PostgresCompare.SQL_SUCCESS)
        report.successful = successful.rows

        const failed = await this.dbi.executeSQL(PostgresCompare.SQL_FAILED)
        report.failed = failed.rows
      }

      if (this.configuration.ddlApplied) {
        report.failed.push(...await this.compareDDL(source,target))
      }
      return report
    }

    async compareDDL(source,target) {

      /*
      **
      ** When the target schema was created from the source schema's DDL, the DDL generated from the target must match the DDL generated from the source,
      ** and no object in the target may depend on an object in the source schema, other than one that belongs to an extension, such as a PostGIS type.
      **
      ** Unqualified names in the target's DDL resolve against the target schema and then the source schema, as they did when the DDL was applied.
      **
      */

      const failed = []
      // A DDL_ONLY operation does not apply the statements that copy state, such as sequence values.
      const ddlOnly = (this.configuration.parameters?.MODE === 'DDL_ONLY') || (this.configuration.ddlApplied === 'DDL_ONLY')
      const isComparable = (ddl) => { return !(ddlOnly && ddl.startsWith(this.dbi.STATEMENT_LIBRARY_CLASS.DATA_MARKER)) }
      const sourceDDL = (await this.dbi.generateDDL(source)).filter(isComparable)
      const targetDDL = (await this.dbi.generateDDL(target,source)).filter(isComparable)

      const unmatched = new Map()
      sourceDDL.forEach((ddl) => { unmatched.set(ddl,(unmatched.get(ddl) || 0) + 1) })
      const unexpected = targetDDL.filter((ddl) => {
        const count = unmatched.get(ddl) || 0
        unmatched.set(ddl,count - 1)
        return count <= 0
      })

      const summarize = (ddl) => { return `DDL: ${ddl.split('\n')[0].replaceAll('%%SCHEMA%%.','').substring(0,64)}` }
      unmatched.forEach((count,ddl) => {
        for (let i = 0; i < count; i++) {
          failed.push([source,target,summarize(ddl),-1,-1,1,0,`Missing: ${ddl}`])
        }
      })
      unexpected.forEach((ddl) => {
        failed.push([source,target,summarize(ddl),-1,-1,0,1,`Unexpected: ${ddl}`])
      })

      const dependencies = await this.dbi.executeSQL(PostgresCompare.SQL_SOURCE_DEPENDENCIES,[source,target])
      dependencies.rows.forEach(([objectType,objectIdentity,references]) => {
        failed.push([source,target,`DDL: ${objectType} ${objectIdentity}`,-1,-1,0,1,`References the source schema: ${references}`])
      })
      return failed
    }
			
}

export { PostgresCompare as default }

const _SQL_SUCCESS =
`select SOURCE_SCHEMA, TARGET_SCHEMA, TABLE_NAME, TARGET_ROW_COUNT
   from SCHEMA_COMPARE_RESULTS 
  where SOURCE_ROW_COUNT = TARGET_ROW_COUNT
    and MISSING_ROWS = 0
    and EXTRA_ROWS = 0
    and SQLERRM is NULL
 order by TABLE_NAME`;

const _SQL_FAILED = 
`select SOURCE_SCHEMA, TARGET_SCHEMA, TABLE_NAME, SOURCE_ROW_COUNT, TARGET_ROW_COUNT, MISSING_ROWS, EXTRA_ROWS,  SQLERRM
   from SCHEMA_COMPARE_RESULTS 
  where SOURCE_ROW_COUNT <> TARGET_ROW_COUNT
     or MISSING_ROWS <> 0
      or EXTRA_ROWS <> 0
    or SQLERRM is NOT NULL
  order by TABLE_NAME`;
  
const _SQL_SCHEMA_TABLE_NAMES = `select relname from pg_stat_user_tables where schemaname = $1`;

// const _SQL_SCHEMA_TABLE_ROWS  = `select schemaname, relname, n_live_tup from pg_stat_user_tables where schemaname = $1`;

// The tables that are exported: partitions are exported through the partitioned table, an inheritance parent's rows exclude its children's, and tables that belong to an extension are not exported.

const _SQL_SCHEMA_TABLE_ROWS =
`with ROW_COUNTS as (
select n.nspname table_schema, c.relname table_name, query_to_xml(format('select count(*) as cnt from %s %I.%I', case when c.relkind = 'r' then 'only' else '' end, n.nspname, c.relname), false, true, '') as xml_count
  from pg_catalog.pg_class c
  join pg_catalog.pg_namespace n
    on n.oid = c.relnamespace
 where n.nspname = $1
   and c.relkind in ('r','p')
   and not c.relispartition
   and not exists (select 1 from pg_catalog.pg_depend d where d.classid = 'pg_catalog.pg_class'::regclass and d.objid = c.oid and d.deptype = 'e')
)
select table_schema, table_name, (xpath('/row/cnt/text()', xml_count))[1]::text::int as row_count
  from ROW_COUNTS`

// Objects in the target schema ($2) that depend on objects in the source schema ($1). pg_identify_object() does not report the schema of a column default or a view's rule, so it is taken from the relation.

const _SQL_SOURCE_DEPENDENCIES =
`select o.type, o.identity, string_agg(distinct r.type || ' ' || r.identity, ', ')
   from pg_catalog.pg_depend d
  cross join lateral pg_catalog.pg_identify_object(d.classid, d.objid, d.objsubid) o
  cross join lateral pg_catalog.pg_identify_object(d.refclassid, d.refobjid, d.refobjsubid) r
  where coalesce(o.schema, (select c.relnamespace::regnamespace::text
                              from pg_catalog.pg_class c
                             where c.oid = case d.classid
                                             when 'pg_catalog.pg_attrdef'::regclass then (select ad.adrelid from pg_catalog.pg_attrdef ad where ad.oid = d.objid)
                                             when 'pg_catalog.pg_rewrite'::regclass then (select rw.ev_class from pg_catalog.pg_rewrite rw where rw.oid = d.objid)
                                           end)) = $2
    and r.schema = $1
    and d.deptype in ('n','a')
    and not exists (select 1 from pg_catalog.pg_depend e where e.classid = d.refclassid and e.objid = d.refobjid and e.deptype = 'e')
  group by o.type, o.identity
  order by o.type, o.identity`

// Columns that are generated in both the source schema ($1) and the target schema ($2): the columns YADAMU.COMPARE_SCHEMA leaves out of the compare when ignoreGeneratedColumns is set. The tables are the ones it compares.

const _SQL_GENERATED_COLUMNS =
`select s.table_name, s.column_name
   from information_schema.columns s
   join information_schema.columns t
     on t.table_name = s.table_name
    and t.column_name = s.column_name
   join information_schema.tables st
     on st.table_schema = s.table_schema
    and st.table_name = s.table_name
  where s.table_schema = $1
    and t.table_schema = $2
    and s.is_generated = 'ALWAYS'
    and t.is_generated = 'ALWAYS'
    and st.table_type = 'BASE TABLE'
    and not exists (select 1 from pg_catalog.pg_depend d where d.classid = 'pg_catalog.pg_class'::regclass and d.objid = format('%I.%I',s.table_schema,s.table_name)::regclass and d.deptype = 'e')
  order by s.table_name, s.ordinal_position`

const _SQL_COMPARE_SCHEMAS    = `call YADAMU.COMPARE_SCHEMA($1,$2,$3)`