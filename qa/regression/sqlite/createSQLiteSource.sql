-- Create HR schema tables
CREATE TABLE IF NOT EXISTS "HR"."COUNTRIES" (
    "COUNTRY_ID" CHAR(2) PRIMARY KEY,
    "COUNTRY_NAME" VARCHAR(40),
    "REGION_ID" INTEGER
);

CREATE TABLE IF NOT EXISTS "HR"."REGIONS" (
    "REGION_ID" INTEGER PRIMARY KEY,
    "REGION_NAME" VARCHAR(25)
);

CREATE TABLE IF NOT EXISTS "HR"."LOCATIONS" (
    "LOCATION_ID" INTEGER PRIMARY KEY,
    "STREET_ADDRESS" VARCHAR(40),
    "POSTAL_CODE" VARCHAR(12),
    "CITY" VARCHAR(30),
    "STATE_PROVINCE" VARCHAR(25),
    "COUNTRY_ID" CHAR(2)
);

CREATE TABLE IF NOT EXISTS "HR"."DEPARTMENTS" (
    "DEPARTMENT_ID" INTEGER PRIMARY KEY,
    "DEPARTMENT_NAME" VARCHAR(30),
    "MANAGER_ID" INTEGER,
    "LOCATION_ID" INTEGER
);

CREATE TABLE IF NOT EXISTS "HR"."JOBS" (
    "JOB_ID" VARCHAR(10) PRIMARY KEY,
    "JOB_TITLE" VARCHAR(35),
    "MIN_SALARY" INTEGER,
    "MAX_SALARY" INTEGER
);

CREATE TABLE IF NOT EXISTS "HR"."EMPLOYEES" (
    "EMPLOYEE_ID" INTEGER PRIMARY KEY,
    "FIRST_NAME" VARCHAR(20),
    "LAST_NAME" VARCHAR(25),
    "EMAIL" VARCHAR(25),
    "PHONE_NUMBER" VARCHAR(20),
    "HIRE_DATE" DATE,
    "JOB_ID" VARCHAR(10),
    "SALARY" INTEGER,
    "COMMISSION_PCT" REAL,
    "MANAGER_ID" INTEGER,
    "DEPARTMENT_ID" INTEGER
);

CREATE TABLE IF NOT EXISTS "HR"."JOB_HISTORY" (
    "EMPLOYEE_ID" INTEGER,
    "START_DATE" DATE,
    "END_DATE" DATE,
    "JOB_ID" VARCHAR(10),
    "DEPARTMENT_ID" INTEGER,
    PRIMARY KEY ("EMPLOYEE_ID", "START_DATE")
);

-- Create BI schema tables
CREATE TABLE IF NOT EXISTS "BI"."CHANNELS" (
    "CHANNEL_ID" INTEGER PRIMARY KEY,
    "CHANNEL_DESC" VARCHAR(20),
    "CHANNEL_CLASS" VARCHAR(20),
    "CHANNEL_CLASS_ID" INTEGER,
    "CHANNEL_TOTAL" VARCHAR(13),
    "CHANNEL_TOTAL_ID" INTEGER
);

CREATE TABLE IF NOT EXISTS "BI"."COUNTRIES" (
    "COUNTRY_ID" INTEGER PRIMARY KEY,
    "COUNTRY_ISO_CODE" CHAR(2),
    "COUNTRY_NAME" VARCHAR(40),
    "COUNTRY_SUBREGION" VARCHAR(30),
    "COUNTRY_SUBREGION_ID" INTEGER,
    "COUNTRY_REGION" VARCHAR(20),
    "COUNTRY_REGION_ID" INTEGER,
    "COUNTRY_TOTAL" VARCHAR(11),
    "COUNTRY_TOTAL_ID" INTEGER
);

CREATE TABLE IF NOT EXISTS "BI"."CUSTOMERS" (
    "CUST_ID" INTEGER PRIMARY KEY,
    "CUST_FIRST_NAME" VARCHAR(20),
    "CUST_LAST_NAME" VARCHAR(40),
    "CUST_GENDER" CHAR(1),
    "CUST_YEAR_OF_BIRTH" INTEGER,
    "CUST_MARITAL_STATUS" VARCHAR(20),
    "CUST_STREET_ADDRESS" VARCHAR(40),
    "CUST_POSTAL_CODE" VARCHAR(10),
    "CUST_CITY" VARCHAR(30),
    "CUST_CITY_ID" INTEGER,
    "CUST_STATE_PROVINCE" VARCHAR(40),
    "CUST_STATE_PROVINCE_ID" INTEGER,
    "COUNTRY_ID" INTEGER,
    "CUST_MAIN_PHONE_NUMBER" VARCHAR(25),
    "CUST_INCOME_LEVEL" VARCHAR(30),
    "CUST_CREDIT_LIMIT" INTEGER,
    "CUST_EMAIL" VARCHAR(30),
    "CUST_TOTAL" VARCHAR(14),
    "CUST_TOTAL_ID" INTEGER,
    "CUST_SRC_ID" INTEGER,
    "CUST_EFF_FROM" DATE,
    "CUST_EFF_TO" DATE,
    "CUST_VALID" VARCHAR(1)
);

CREATE TABLE IF NOT EXISTS "BI"."PRODUCTS" (
    "PROD_ID" INTEGER PRIMARY KEY,
    "PROD_NAME" VARCHAR(50),
    "PROD_DESC" VARCHAR(4000),
    "PROD_SUBCATEGORY" VARCHAR(50),
    "PROD_SUBCATEGORY_ID" INTEGER,
    "PROD_SUBCATEGORY_DESC" VARCHAR(2000),
    "PROD_CATEGORY" VARCHAR(50),
    "PROD_CATEGORY_ID" INTEGER,
    "PROD_CATEGORY_DESC" VARCHAR(2000),
    "PROD_WEIGHT_CLASS" INTEGER,
    "PROD_UNIT_OF_MEASURE" VARCHAR(20),
    "PROD_PACK_SIZE" VARCHAR(30),
    "SUPPLIER_ID" INTEGER,
    "PROD_STATUS" VARCHAR(20),
    "PROD_LIST_PRICE" INTEGER,
    "PROD_MIN_PRICE" INTEGER,
    "PROD_TOTAL" VARCHAR(13),
    "PROD_TOTAL_ID" INTEGER,
    "PROD_SRC_ID" INTEGER,
    "PROD_EFF_FROM" DATE,
    "PROD_EFF_TO" DATE,
    "PROD_VALID" VARCHAR(1)
);

CREATE TABLE IF NOT EXISTS "BI"."PROMOTIONS" (
    "PROMO_ID" INTEGER PRIMARY KEY,
    "PROMO_NAME" VARCHAR(30),
    "PROMO_SUBCATEGORY" VARCHAR(30),
    "PROMO_SUBCATEGORY_ID" INTEGER,
    "PROMO_CATEGORY" VARCHAR(30),
    "PROMO_CATEGORY_ID" INTEGER,
    "PROMO_COST" INTEGER,
    "PROMO_BEGIN_DATE" DATE,
    "PROMO_END_DATE" DATE,
    "PROMO_TOTAL" VARCHAR(13),
    "PROMO_TOTAL_ID" INTEGER
);

CREATE TABLE IF NOT EXISTS "BI"."SALES" (
    "PROD_ID" INTEGER,
    "CUST_ID" INTEGER,
    "TIME_ID" DATE,
    "CHANNEL_ID" INTEGER,
    "PROMO_ID" INTEGER,
    "QUANTITY_SOLD" INTEGER,
    "AMOUNT_SOLD" REAL,
    PRIMARY KEY ("PROD_ID", "CUST_ID", "TIME_ID", "CHANNEL_ID", "PROMO_ID")
);

CREATE TABLE IF NOT EXISTS "BI"."TIMES" (
    "TIME_ID" DATE PRIMARY KEY,
    "DAY_NAME" VARCHAR(10),
    "DAY_NUMBER_IN_WEEK" INTEGER,
    "DAY_NUMBER_IN_MONTH" INTEGER,
    "CALENDAR_WEEK_NUMBER" INTEGER,
    "FISCAL_WEEK_NUMBER" INTEGER,
    "WEEK_ENDING_DAY" DATE,
    "WEEK_ENDING_DAY_ID" INTEGER,
    "CALENDAR_MONTH_NUMBER" INTEGER,
    "FISCAL_MONTH_NUMBER" INTEGER,
    "CALENDAR_MONTH_DESC" VARCHAR(10),
    "CALENDAR_MONTH_ID" INTEGER,
    "FISCAL_MONTH_DESC" VARCHAR(10),
    "FISCAL_MONTH_ID" INTEGER,
    "DAYS_IN_CAL_MONTH" INTEGER,
    "DAYS_IN_FIS_MONTH" INTEGER,
    "END_OF_CAL_MONTH" DATE,
    "END_OF_FIS_MONTH" DATE,
    "CALENDAR_MONTH_NAME" VARCHAR(10),
    "FISCAL_MONTH_NAME" VARCHAR(10),
    "CALENDAR_QUARTER_DESC" CHAR(7),
    "CALENDAR_QUARTER_ID" INTEGER,
    "FISCAL_QUARTER_DESC" CHAR(7),
    "FISCAL_QUARTER_ID" INTEGER,
    "DAYS_IN_CAL_QUARTER" INTEGER,
    "DAYS_IN_FIS_QUARTER" INTEGER,
    "END_OF_CAL_QUARTER" DATE,
    "END_OF_FIS_QUARTER" DATE,
    "CALENDAR_QUARTER_NUMBER" INTEGER,
    "FISCAL_QUARTER_NUMBER" INTEGER,
    "CALENDAR_YEAR" INTEGER,
    "CALENDAR_YEAR_ID" INTEGER,
    "FISCAL_YEAR" INTEGER,
    "FISCAL_YEAR_ID" INTEGER,
    "DAYS_IN_CAL_YEAR" INTEGER,
    "DAYS_IN_FIS_YEAR" INTEGER,
    "END_OF_CAL_YEAR" DATE,
    "END_OF_FIS_YEAR" DATE
);

